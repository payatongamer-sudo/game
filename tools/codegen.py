#!/usr/bin/env python3
"""Generate C# from the sheets: one record type per sheet, one instance per row.

    python3 tools/codegen.py   # writes src/BrewingPoint.Core/Generated/Sheets.g.cs

Column types are inferred from the cells: all ints -> int, numbers -> float,
true/false -> bool, lists -> string[], numbers mixed with a 'game'/'none'
sentinel -> nullable number (null for the sentinel), everything else -> string.
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "BrewingPoint.Core" / "Generated" / "Sheets.g.cs"
SENTINELS = {"game", "none"}


def pascal(name):
    return "".join(part[:1].upper() + part[1:] for part in name.replace("-", "_").split("_"))


def column_type(values):
    non_sentinel = [v for v in values if not (isinstance(v, str) and v in SENTINELS)]
    nullable = len(non_sentinel) != len(values)
    if all(isinstance(v, list) for v in values):
        return "string[]", False
    if non_sentinel and all(isinstance(v, bool) for v in non_sentinel):
        return "bool", nullable
    if non_sentinel and all(isinstance(v, int) and not isinstance(v, bool) for v in non_sentinel):
        return "int", nullable
    if non_sentinel and all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in non_sentinel):
        return "float", nullable
    return "string", False


def literal(value, ctype, nullable):
    if ctype == "string[]":
        return "new[] { " + ", ".join(json.dumps(str(v)) for v in value) + " }"
    if nullable and isinstance(value, str) and value in SENTINELS:
        return "null"
    if ctype == "bool":
        return "true" if value else "false"
    if ctype == "int":
        return str(int(value))
    if ctype == "float":
        return repr(float(value)) + "f"
    return json.dumps(str(value))


def main():
    if subprocess.run([sys.executable, str(ROOT / "tools" / "preflight.py")]).returncode != 0:
        print("codegen: preflight failed, nothing generated")
        return 1
    lines = [
        "// <auto-generated> from sheets/*.json by tools/codegen.py. Edit the sheets, not this file. </auto-generated>",
        "#nullable enable",
        "namespace BrewingPoint.Data",
        "{",
    ]
    tables = []
    for path in sorted((ROOT / "sheets").glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        sheet, columns, rows = data["sheet"], list(data["columns"]), data["rows"]
        record = pascal(sheet) + "Row"
        types = {c: column_type([r[c] for r in rows]) for c in columns}
        params = []
        for c in columns:
            ctype, nullable = types[c]
            params.append(f"{ctype}{'?' if nullable else ''} {pascal(c)}")
        lines.append(f"    /// <summary>{data.get('about', sheet)}</summary>")
        lines.append(f"    public sealed record {record}({', '.join(params)});")
        lines.append("")
        body = []
        for r in rows:
            args = ", ".join(literal(r[c], *types[c]) for c in columns)
            body.append(f"            new {record}({args}),")
        tables.append((pascal(sheet), record, body))
    lines.append("    public static class Sheets")
    lines.append("    {")
    for name, record, body in tables:
        lines.append(f"        public static readonly {record}[] {name} =")
        lines.append("        {")
        lines.extend(body)
        lines.append("        };")
        lines.append("")
    lines[-1] = "    }"
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"codegen: wrote {OUT.relative_to(ROOT)} ({sum(len(t[2]) for t in tables)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
